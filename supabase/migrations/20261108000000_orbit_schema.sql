-- New public tables are not exposed by default on current Supabase projects;
-- the grants above make only the intended tables usable by authenticated clients.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    begin
      alter publication supabase_realtime add table public.workspace_members, public.projects,
        public.issues, public.issue_comments, public.issue_activity;
    exception when duplicate_object then
      null;
    end;
  end if;
end;
$$;
