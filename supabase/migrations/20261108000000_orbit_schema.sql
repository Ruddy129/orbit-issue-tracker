-- Orbit issue tracker: workspace-scoped data with authenticated access only.
-- All tables exposed through the Supabase Data API use RLS and explicit grants.

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default 'Team member',
  created_at timestamptz not null default now()
);

create table public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 2 and 60),
  created_by uuid not null references auth.users (id) on delete restrict,
  created_at timestamptz not null default now()
);

create table public.workspace_members (
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'admin', 'member')),
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  name text not null check (char_length(trim(name)) between 2 and 60),
  key text not null check (key ~ '^[A-Z0-9]{2,6}$'),
  color text not null default '#7562dd',
  description text not null default '',
  created_by uuid not null references auth.users (id) on delete restrict,
  created_at timestamptz not null default now(),
  unique (workspace_id, key),
  unique (id, workspace_id)
);

create table public.issues (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  project_id uuid not null,
  issue_number bigint generated by default as identity,
  key text not null,
  title text not null check (char_length(trim(title)) between 1 and 120),
  description text not null default '',
  status text not null default 'backlog' check (status in ('backlog', 'in-progress', 'review', 'done')),
  priority text not null default 'medium' check (priority in ('urgent', 'high', 'medium', 'low')),
  assignee_id uuid references public.profiles (id) on delete set null,
  due_date date,
  created_by uuid not null references auth.users (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint issues_project_workspace_fk foreign key (project_id, workspace_id)
    references public.projects (id, workspace_id) on delete cascade,
  unique (project_id, key),
  unique (id, workspace_id)
);

create table public.issue_comments (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  issue_id uuid not null,
  author_id uuid not null references public.profiles (id) on delete restrict,
  body text not null check (char_length(trim(body)) between 1 and 3000),
  created_at timestamptz not null default now(),
  constraint comments_issue_workspace_fk foreign key (issue_id, workspace_id)
    references public.issues (id, workspace_id) on delete cascade
);

create table public.issue_activity (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  issue_id uuid not null,
  actor_id uuid references public.profiles (id) on delete set null,
  event_type text not null check (event_type in ('status_changed', 'priority_changed', 'assignee_changed')),
  old_value jsonb,
  new_value jsonb,
  created_at timestamptz not null default now(),
  constraint activity_issue_workspace_fk foreign key (issue_id, workspace_id)
    references public.issues (id, workspace_id) on delete cascade
);

create table public.workspace_invites (
  token text primary key,
  workspace_id uuid not null references public.workspaces (id) on delete cascade,
  created_by uuid not null references public.profiles (id) on delete cascade,
  expires_at timestamptz not null,
  use_count integer not null default 0 check (use_count >= 0),
  max_uses integer not null default 25 check (max_uses between 1 and 100),
  created_at timestamptz not null default now()
);

create index workspace_members_user_idx on public.workspace_members (user_id, workspace_id);
create index projects_workspace_idx on public.projects (workspace_id, name);
create index issues_workspace_status_idx on public.issues (workspace_id, status, created_at desc);
create index issues_assignee_idx on public.issues (workspace_id, assignee_id);
create index issue_comments_issue_idx on public.issue_comments (issue_id, created_at);
create index issue_activity_issue_idx on public.issue_activity (issue_id, created_at);

-- Narrow SECURITY DEFINER helpers are used only to avoid recursive RLS checks.
-- Their fixed search_path and explicit grants keep them from becoming general-purpose bypasses.
create or replace function public.is_workspace_member(target_workspace_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = target_workspace_id
      and wm.user_id = (select auth.uid())
  );
$$;

create or replace function public.is_workspace_admin(target_workspace_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.workspace_members wm
    where wm.workspace_id = target_workspace_id
      and wm.user_id = (select auth.uid())
      and wm.role in ('owner', 'admin')
  );
$$;

create or replace function public.shares_workspace_with(target_user_id uuid)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.workspace_members mine
    join public.workspace_members theirs using (workspace_id)
    where mine.user_id = (select auth.uid())
      and theirs.user_id = target_user_id
  );
$$;

create or replace function public.touch_updated_at()
returns trigger language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.handle_new_auth_user()
returns trigger language plpgsql security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (
    new.id,
    coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'Team member'
    )
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create or replace function public.assign_issue_key()
returns trigger language plpgsql security definer
set search_path = ''
as $$
declare
  project_key text;
begin
  select p.key into project_key
  from public.projects p
  where p.id = new.project_id and p.workspace_id = new.workspace_id;
  if project_key is null then
    raise exception 'Project does not belong to this workspace';
  end if;
  new.key := project_key || '-' || new.issue_number::text;
  return new;
end;
$$;

create or replace function public.log_issue_changes()
returns trigger language plpgsql security definer
set search_path = ''
as $$
begin
  if old.status is distinct from new.status then
    insert into public.issue_activity (workspace_id, issue_id, actor_id, event_type, old_value, new_value)
    values (new.workspace_id, new.id, (select auth.uid()), 'status_changed', to_jsonb(old.status), to_jsonb(new.status));
  end if;
  if old.priority is distinct from new.priority then
    insert into public.issue_activity (workspace_id, issue_id, actor_id, event_type, old_value, new_value)
    values (new.workspace_id, new.id, (select auth.uid()), 'priority_changed', to_jsonb(old.priority), to_jsonb(new.priority));
  end if;
  if old.assignee_id is distinct from new.assignee_id then
    insert into public.issue_activity (workspace_id, issue_id, actor_id, event_type, old_value, new_value)
    values (new.workspace_id, new.id, (select auth.uid()), 'assignee_changed', to_jsonb(old.assignee_id), to_jsonb(new.assignee_id));
  end if;
  return new;
end;
$$;

create or replace function public.create_workspace_invite(target_workspace_id uuid)
returns text language plpgsql security definer
set search_path = ''
as $$
declare
  invite_token text;
begin
  if not public.is_workspace_admin(target_workspace_id) then
    raise exception 'Only a workspace admin can create an invite';
  end if;
  invite_token := replace(gen_random_uuid()::text, '-', '') || replace(gen_random_uuid()::text, '-', '');
  insert into public.workspace_invites (token, workspace_id, created_by, expires_at)
  values (invite_token, target_workspace_id, (select auth.uid()), now() + interval '7 days');
  return invite_token;
end;
$$;

create or replace function public.accept_workspace_invite(invite_token text)
returns uuid language plpgsql security definer
set search_path = ''
as $$
declare
  invite_row public.workspace_invites%rowtype;
  inserted_rows integer;
begin
  if (select auth.uid()) is null then
    raise exception 'Sign in before accepting a workspace invite';
  end if;
  select * into invite_row
  from public.workspace_invites wi
  where wi.token = invite_token
    and wi.expires_at > now()
    and wi.use_count < wi.max_uses
  for update;
  if not found then
    raise exception 'This workspace invite is invalid, expired, or full';
  end if;
  insert into public.workspace_members (workspace_id, user_id, role)
  values (invite_row.workspace_id, (select auth.uid()), 'member')
  on conflict (workspace_id, user_id) do nothing;
  get diagnostics inserted_rows = row_count;
  if inserted_rows > 0 then
    update public.workspace_invites set use_count = use_count + 1 where token = invite_row.token;
  end if;
  return invite_row.workspace_id;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

create trigger issues_assign_key
  before insert or update of project_id, workspace_id on public.issues
  for each row execute function public.assign_issue_key();

create trigger issues_touch_updated_at
  before update on public.issues
  for each row execute function public.touch_updated_at();

create trigger issues_log_changes
  after update on public.issues
  for each row execute function public.log_issue_changes();

